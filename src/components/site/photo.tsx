import type { CSSProperties } from "react";
import { photos, type PhotoSlot } from "@/content/images";

interface ArtDirection {
  /** Media query for which `slot` replaces the default crop, e.g. "(min-width: 768px)". */
  media: string;
  slot: PhotoSlot;
  sizes: string;
}

interface PhotoProps {
  slot: PhotoSlot;
  /** Rendered (cover-scaled) width per breakpoint — docs/art-direction.md §7. */
  sizes: string;
  /** A different crop of the same photograph above a breakpoint. */
  art?: ArtDirection;
  /** Only the hero: eager, high fetch priority. Everything else is lazy. */
  priority?: boolean;
  className?: string;
  style?: CSSProperties;
}

const srcSet = (slot: PhotoSlot, ext: "avif" | "webp") =>
  photos[slot].widths.map((w) => `/images/${slot}-${w}.${ext} ${w}w`).join(", ");

/**
 * Responsive, pre-optimized photograph (AVIF first, WebP fallback) generated by
 * `npm run images:build`. The parent frame sets the aspect ratio and the image
 * covers it. Intrinsic width and height prevent layout shift.
 */
export function Photo({ slot, sizes, art, priority, className, style }: PhotoProps) {
  const photo = photos[slot];
  const fallback =
    photo.widths.find((w) => w >= 960) ?? photo.widths[photo.widths.length - 1];
  return (
    <picture>
      {art && (
        <>
          <source
            media={art.media}
            type="image/avif"
            srcSet={srcSet(art.slot, "avif")}
            sizes={art.sizes}
          />
          <source
            media={art.media}
            type="image/webp"
            srcSet={srcSet(art.slot, "webp")}
            sizes={art.sizes}
          />
        </>
      )}
      <source type="image/avif" srcSet={srcSet(slot, "avif")} sizes={sizes} />
      <source type="image/webp" srcSet={srcSet(slot, "webp")} sizes={sizes} />
      {/* Static export: images are pre-optimized at build time, not by next/image. */}
      <img
        src={`/images/${slot}-${fallback}.webp`}
        width={photo.width}
        height={photo.height}
        alt={photo.alt}
        loading={priority ? "eager" : "lazy"}
        fetchPriority={priority ? "high" : "auto"}
        decoding="async"
        className={className}
        style={style}
      />
    </picture>
  );
}
